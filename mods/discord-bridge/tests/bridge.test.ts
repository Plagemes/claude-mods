test('a prompt from the channel asks "Run this?" (reply yes, or react ✅), runs as the owner’s words, and the answer comes back', { plugins, options: OPTIONS }, async ($, on) => {
  const seen = world(on, { files: configured({ [`${DIR}/prefs.json`]: '{}' }) })
  await lead($, seen)
  say(seen, { user: OWNER, text: 'fai il deploy di staging' })
  await pass(seen, 8_000)
  expect(seen.submitted).toEqual([])
  const question = posts(seen).at(-1)
  expect(question?.text).toContain('Run this on **#login**')
  expect(botReactions(seen, question?.id ?? '')).toEqual(['✅', '❌'])
  say(seen, { user: OWNER, text: 'sì' })
  await pass(seen, 8_000)
  expect(seen.submitted).toEqual([{ text: 'fai il deploy di staging', asUser: true }])
  await $.turn.start({ text: 'fai il deploy di staging', turnId: 't1' })
  await $.turn.complete({ answer: 'Deployed to staging.', durationMs: 20_000, isAborted: false, turnId: 't1', reason: 'answer' })
  expect(posts(seen).at(-1)?.text).toContain('Deployed to staging.')

  // A reaction works as well, and a ❌ cancels.
  say(seen, { user: OWNER, text: 'run the linter' })
  await pass(seen, 8_000)
  react(seen, posts(seen).at(-1)?.id ?? '', OWNER, '✅')
  await pass(seen, 12_000)
  expect(seen.submitted.at(-1)).toEqual({ text: 'run the linter', asUser: true })
  say(seen, { user: OWNER, text: 'delete the build folder' })
  await pass(seen, 8_000)
  react(seen, posts(seen).at(-1)?.id ?? '', OWNER, '❌')
  await pass(seen, 12_000)
  expect(seen.submitted).toHaveLength(2)
  expect(posts(seen).at(-1)?.text).toContain('Cancelled')
})

